/**
 * Searches the registry by IEEE Member ID or full name.
 * 
 * @param {string} query 
 * @returns {Object|null}
 */
export function findTeamMember(query) {
  if (!query || typeof query !== 'string') return null;
  const clean = query.trim().toLowerCase();

  // Search by exact or partial member ID
  const byId = IEEE_TEAM_REGISTRY.find(
    (m) => m.memberId && m.memberId.toLowerCase() === clean
  );
  if (byId) return byId;

  // Search by normalized name
  const cleanName = clean.replace(/[^a-z0-9]/g, '');
  const byName = IEEE_TEAM_REGISTRY.find((m) => {
    const regName = m.name.toLowerCase().replace(/[^a-z0-9]/g, '');
    return regName === cleanName || regName.includes(cleanName) || cleanName.includes(regName);
  });
  if (byName) return byName;

  return null;
}
